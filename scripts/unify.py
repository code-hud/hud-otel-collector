#!/usr/bin/env python3
"""Builds deploy/aws/unified-ecs.yaml from observability.yaml, ecs-fargate.yaml and hud-access.yaml, so the
one-click stack can't drift from the separate ones. Every parameter that an observability output says to
"Pass to the ... as <X>" is replaced by that output's value; conditions on those parameters are resolved. --check fails if the committed file is stale (run by test/deploy.sh)."""
import copy, re, sys
from pathlib import Path

import yaml

AWS = Path(__file__).resolve().parent.parent / "deploy" / "aws"
OUT = AWS / "unified-ecs.yaml"
CONSUMERS = ["ecs-fargate.yaml", "hud-access.yaml"]
HEADER = "# Generated by scripts/unify.py from observability.yaml, ecs-fargate.yaml and hud-access.yaml. Do not edit.\n"
DESCRIPTION = ("Hud OpenTelemetry collector on ECS Fargate plus the Observability Stack it writes to (OpenSearch "
               "Serverless, OpenSearch Ingestion, Amazon Managed Service for Prometheus, OpenSearch UI) and a read-only role "
               "Hud can assume to query it, in one stack.")


class Tag:
    def __init__(self, tag, value):
        self.tag, self.value = tag, value

    def __eq__(self, other):
        return isinstance(other, Tag) and (self.tag, self.value) == (other.tag, other.value)


class Loader(yaml.SafeLoader):
    pass


def construct(loader, suffix, node):
    if isinstance(node, yaml.ScalarNode):
        value = loader.construct_scalar(node)
    elif isinstance(node, yaml.SequenceNode):
        value = loader.construct_sequence(node, deep=True)
    else:
        value = loader.construct_mapping(node, deep=True)
    return Tag("!" + suffix, value)


Loader.add_multi_constructor("!", construct)


class Dumper(yaml.SafeDumper):
    def ignore_aliases(self, data):
        return True


def represent_tag(dumper, t):
    if isinstance(t.value, list):
        return dumper.represent_sequence(t.tag, t.value)
    if isinstance(t.value, dict):
        return dumper.represent_mapping(t.tag, t.value)
    return dumper.represent_scalar(t.tag, t.value, style="|" if "\n" in t.value else None)


def represent_str(dumper, s):
    return dumper.represent_scalar("tag:yaml.org,2002:str", s, style="|" if "\n" in s else None)


Dumper.add_representer(Tag, represent_tag)
Dumper.add_representer(str, represent_str)


def load(name):
    return yaml.load((AWS / name).read_text(), Loader)


def walk(x, f):
    x = f(x)
    if isinstance(x, Tag):
        return Tag(x.tag, walk(x.value, f))
    if isinstance(x, list):
        return [walk(v, f) for v in x]
    if isinstance(x, dict):
        return {k: walk(v, f) for k, v in x.items()}
    return x


def refs(x):
    found = set()

    def f(n):
        if isinstance(n, Tag) and n.tag == "!Ref":
            found.add(n.value)
        if isinstance(n, Tag) and n.tag == "!Sub":
            s, local = (n.value, {}) if isinstance(n.value, str) else n.value
            found.update(set(re.findall(r"\$\{([\w:.]+)\}", s)) - set(local))
        return n

    walk(x, f)
    return found


def merge(*templates):
    out = {}
    for t in templates:
        for section in ("Parameters", "Rules", "Conditions", "Resources", "Outputs"):
            for k, v in t.get(section, {}).items():
                assert k not in out.setdefault(section, {}) or out[section][k] == v or section == "Parameters", (section, k)
                out[section][k] = v
        groups = t.get("Metadata", {}).get("AWS::CloudFormation::Interface", {}).get("ParameterGroups", [])
        out.setdefault("Groups", []).extend(groups)
    return out


def build():
    obs = load("observability.yaml")
    used_by = merge(*(load(n) for n in CONSUMERS))
    bound = {}
    for k, o in obs["Outputs"].items():
        m = re.match(r"Pass to the .* as (\w+)\.", o.get("Description", ""))
        if m:
            bound[m.group(1)] = o["Value"]
    assert set(bound) <= set(used_by["Parameters"]), bound.keys()

    # A bound parameter is never empty, so: Equals[Ref p, ""] is false.
    def cond(e):
        if e.tag == "!Not":
            return not cond(e.value[0])
        a, b = e.value
        assert e.tag == "!Equals" and isinstance(a, Tag) and a.tag == "!Ref" and a.value in bound and b == "", e
        return False

    fixed = {k: cond(v) for k, v in used_by["Conditions"].items() if refs(v) & set(bound)}

    def sub_var(expr):
        if expr.tag == "!Ref":
            return expr.value
        if expr.tag == "!GetAtt":
            return expr.value

    def rewrite(n):
        if not isinstance(n, Tag):
            return n
        if n.tag == "!If" and n.value[0] in fixed:
            return rewrite(n.value[1] if fixed[n.value[0]] else n.value[2])
        if n.tag == "!Ref" and n.value in bound:
            return copy.deepcopy(bound[n.value])
        if n.tag == "!Sub":
            s, vars = (n.value, {}) if isinstance(n.value, str) else (n.value[0], dict(n.value[1]))
            for p in set(re.findall(r"\$\{(\w+)\}", s)) & set(bound) - set(vars):
                name = sub_var(bound[p])
                if name:
                    s = s.replace("${%s}" % p, "${%s}" % name)
                else:
                    vars[p] = copy.deepcopy(bound[p])
            return Tag("!Sub", [s, vars] if vars else s)
        return n

    resources = {k: {a: b for a, b in v.items() if not (a == "Condition" and b in fixed)}
                 for k, v in used_by["Resources"].items() if fixed.get(v.get("Condition"), True)}
    resources = walk(resources, rewrite)
    assert not set(obs["Resources"]) & set(resources), set(obs["Resources"]) & set(resources)

    outputs = walk(used_by["Outputs"], rewrite)
    for k, o in obs["Outputs"].items():
        if o.get("Description", "").startswith("Pass to the "):
            continue
        outputs["Observability" + k if k in outputs else k] = o

    groups = [{"Label": {"default": "Observability Stack"}, "Parameters": list(obs["Parameters"])}]
    for g in used_by["Groups"]:
        ps = [p for p in g["Parameters"] if p not in bound]
        if ps:
            groups.append({**g, "Parameters": ps})

    t = {
        "AWSTemplateFormatVersion": obs["AWSTemplateFormatVersion"],
        "Description": DESCRIPTION,
        "Metadata": {"AWS::CloudFormation::Interface": {"ParameterGroups": groups}},
        "Parameters": {**obs["Parameters"], **{k: v for k, v in used_by["Parameters"].items() if k not in bound}},
        "Rules": {k: v for k, v in used_by.get("Rules", {}).items() if not refs(v) & set(bound)},
        "Conditions": {k: v for k, v in used_by["Conditions"].items() if k not in fixed},
        "Resources": {**obs["Resources"], **resources},
        "Outputs": outputs,
    }
    t = {k: v for k, v in t.items() if v}
    used = {r.get("Condition") for r in t["Resources"].values()}

    def ifs(n):
        if isinstance(n, Tag) and n.tag == "!If":
            used.add(n.value[0])
        return n

    walk(t, ifs)
    leftover = refs(t) & set(bound) | used & set(fixed)
    assert not leftover, leftover
    return HEADER + yaml.dump(t, Dumper=Dumper, sort_keys=False, width=1000, allow_unicode=True)


if __name__ == "__main__":
    text = build()
    if sys.argv[1:] == ["--check"]:
        if OUT.read_text() != text:
            sys.exit(f"{OUT.name} is stale: run scripts/unify.py")
        print(f"ok: {OUT.name}")
    else:
        OUT.write_text(text)
